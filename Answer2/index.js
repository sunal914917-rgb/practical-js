
let a = 20;
let b = 10;

// Arithmetic Operators
console.log("Addition:", a + b);
console.log("Subtraction:", a - b);
console.log("Multiplication:", a * b);
console.log("Division:", a / b);
console.log("Modulus:", a % b);

// Comparison Operators
console.log("Greater than:", a > b);
console.log("Equal:", a == b);

// Logical Operators
console.log("Logical AND:", a > 5 && b > 5);
console.log("Logical OR:", a > 25 || b > 5);

// Type Conversion
let num = "100";
let convertedNum = Number(num);

console.log("Original Value:", num);
console.log("Original Type:", typeof num);
console.log("Converted Value:", convertedNum);
console.log("Converted Type:", typeof convertedNum);

// Simple Calculator
let num1 = 50;
let num2 = 25;

console.log("Calculator Addition:", num1 + num2);
console.log("Calculator Subtraction:", num1 - num2);
console.log("Calculator Multiplication:", num1 * num2);
console.log("Calculator Division:", num1 / num2);
