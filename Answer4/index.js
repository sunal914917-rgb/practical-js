
function greet() {
    console.log("Hello JavaScript");
}

function add(a, b) {
    return a + b;
}

function square(n) {
    return n * n;
}

const multiply = (a, b) => a * b;

greet();
console.log("Addition:", add(10, 20));
console.log("Square:", square(5));
console.log("Multiplication:", multiply(4, 5));
